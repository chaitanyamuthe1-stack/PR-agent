_STATIC_CACHE: Dict[str, Dict[str, Any]] = {}
_STATIC_CACHE_LOCK = threading.Lock()
MAX_STATIC_CACHE = 256

_CACHE_STATS = {
    "hits": 0,
    "misses": 0,
    "total_queries": 0
}
_TOOL_VERSIONS_CACHE: Dict[str, str] = {}
_TOOL_VERSIONS_LOCK = threading.Lock()


def get_static_cache_stats() -> Dict[str, Any]:
    """Returns telemetry on static analysis cache hits, misses, and hit rate."""
    with _STATIC_CACHE_LOCK:
        total = _CACHE_STATS["total_queries"]
        hits = _CACHE_STATS["hits"]
        misses = _CACHE_STATS["misses"]
        hit_rate = round((hits / total), 4) if total > 0 else 0.0
        return {
            "hits": hits,
            "misses": misses,
            "total_queries": total,
            "hit_rate": hit_rate,
            "cache_size": len(_STATIC_CACHE),
            "max_cache_size": MAX_STATIC_CACHE
        }


def clear_static_cache():
    """Flushes static analysis LRU cache and resets query statistics."""
    with _STATIC_CACHE_LOCK:
        _STATIC_CACHE.clear()
        _CACHE_STATS["hits"] = 0
        _CACHE_STATS["misses"] = 0
        _CACHE_STATS["total_queries"] = 0


def _get_tool_versions_hash_for_lang(lang: str) -> str:
    """Returns a deterministic SHA-256 hash of installed tool paths and versions for language."""
    target_tools = LANGUAGE_TOOL_MAPPING.get(lang, ["pylint"])
    parts = []
    with _TOOL_VERSIONS_LOCK:
        for t in sorted(target_tools):
            if t in _TOOL_VERSIONS_CACHE:
                parts.append(_TOOL_VERSIONS_CACHE[t])
            else:
                exe = shutil.which(t)
                ver = ""
                if exe:
                    try:
                        p = subprocess.run([exe, "--version"], capture_output=True, text=True, timeout=2)
                        ver = p.stdout.splitlines()[0].strip() if p.stdout else "installed"
                    except Exception:
                        ver = "installed"
                entry = f"{t}:{exe or 'missing'}:{ver}"
                _TOOL_VERSIONS_CACHE[t] = entry
                parts.append(entry)
    return hashlib.sha256(";".join(parts).encode("utf-8")).hexdigest()[:16]


def _get_tool_config_hash_for_lang(lang: str) -> str:
    """Returns a deterministic configuration hash for the language linter arguments."""
    configs = {
        "python": "pylint:E,W,C0301,R0903|bandit:json_q",
        "cpp": "cppcheck:enable=all,inconclusive|g++:fsyntax-only,Wall,Wextra",
        "c": "cppcheck:enable=all,inconclusive|gcc:fsyntax-only,Wall,Wextra",
        "java": "checkstyle:sun_checks|javac:Xlint_all",
        "javascript": "eslint:recommended|node:check",
        "ruby": "rubocop:format_json|ruby:c"
    }
    raw = configs.get(lang, "default")
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()[:16]


