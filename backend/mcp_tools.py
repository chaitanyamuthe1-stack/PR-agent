"""
MCP Static Analysis Layer for PR Agent.
Invokes deterministic linters per language before any LLM inference:
- Python: bandit (security) + pylint (code quality) + safe AST compile
- C and C++: cppcheck (static analyzer) + optional safe compiler syntax check (g++ / gcc -fsyntax-only)
- Java: checkstyle (code standards) + optional safe compilation check (javac -d <temp> -Xlint:all)
- JavaScript: eslint (linter) + optional safe syntax check (node --check)
- Ruby: rubocop (linter) + optional safe syntax check (ruby -c)

Truthful execution model:
- Real native tools run when found in PATH.
- Tools missing in PATH are truthfully reported as "unavailable" with exit_code=None, execution_time=0.0ms.
- Built-in deterministic pattern analysis provides cross-platform zero-dependency baseline coverage.
- Findings generated by built-in engines are tagged with tool_available=False and evidence_type="builtin_pattern_rule".
- Safe syntax and compiler checks run in isolated environments without executing untrusted application logic.
"""

