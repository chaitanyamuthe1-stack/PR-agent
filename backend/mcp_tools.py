def _deterministic_java_scan(code: str) -> List[Dict[str, Any]]:
    """Deterministic Java static analysis engine matching Checkstyle and security rule IDs."""
    findings = []
    lines = code.split("\n")
    for i, line in enumerate(lines, 1):
        code_line = line.split("//")[0].strip()
        if not code_line:
            continue

        # 1. SQL Injection (CWE-89)
        if re.search(r'String\s+sql\s*=.*(SELECT|UPDATE|INSERT|DELETE).*WHERE.*\+', code_line, re.IGNORECASE) or re.search(r'executeUpdate\(.*WHERE.*\+', code_line):
            findings.append(normalize_finding(
                tool="checkstyle (builtin analyzer)",
                rule_id="checkstyle:SqlInjection",
                line=i,
                message="String concatenation detected in SQL statement; use PreparedStatement",
                severity="critical",
                category="security",
                cwe="CWE-89",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        # 2. Hardcoded Credentials (CWE-798)
        if re.search(r'(DB_SECRET|PASSWORD|SECRET_KEY|API_KEY|API_SECRET|SECRET|TOKEN|KEY)\s*=\s*["\'][A-Za-z0-9_\-]{16,}["\']', code_line, re.IGNORECASE) or re.search(r'(?:String|final)\s+[a-zA-Z0-9_]*\s*=\s*["\'](sk_live_|AIza|SECRET_|API_|ghp_|gho_|HARDCODED)[A-Za-z0-9_\-]{10,}["\']', code_line, re.IGNORECASE):
            findings.append(normalize_finding(
                tool="checkstyle (builtin analyzer)",
                rule_id="checkstyle:HardcodedConstant",
                line=i,
                message="Hardcoded database secret token or sensitive credential in Java class",
                severity="high",
                category="security",
                cwe="CWE-798",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        # 3. Unclosed FileInputStream / Resource Leak (CWE-404)
        if "FileInputStream" in code_line and "try (" not in code and "try(" not in code:
            findings.append(normalize_finding(
                tool="checkstyle (builtin analyzer)",
                rule_id="checkstyle:ResourceLeak",
                line=i,
                message="Unclosed FileInputStream; use try-with-resources statement to guarantee closure",
                severity="medium",
                category="bug",
                cwe="CWE-404",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        # 4. Swallowed Exception / Empty Catch (CWE-390)
        if re.search(r'catch\s*\([^\)]+\)\s*\{\s*\}', code_line) or re.search(r'catch\s*\([^\)]+\)\s*\{\s*//[^\n]*\s*\}', code_line):
            findings.append(normalize_finding(
                tool="checkstyle (builtin analyzer)",
                rule_id="checkstyle:EmptyBlock",
                line=i,
                message="Empty catch block swallows exception without logging or re-throwing",
                severity="medium",
                category="bug",
                cwe="CWE-390",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        # 5. String comparison with == (CWE-595, Logic)
        if re.search(r'([a-zA-Z0-9_]+)\s*==\s*["\'][^"\']+["\']', code_line) or re.search(r'["\'][^"\']+["\']\s*==\s*([a-zA-Z0-9_]+)', code_line):
            findings.append(normalize_finding(
                tool="checkstyle (builtin analyzer)",
                rule_id="checkstyle:StringComparison",
                line=i,
                message="Strings compared using '==' (reference equality) instead of '.equals()' (value equality)",
                severity="high",
                category="bug",
                cwe="CWE-595",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        # 6. Null Pointer Dereference risk (CWE-476)
        if re.search(r'public\s+.*\(\s*String\s+([a-zA-Z0-9_]+).*\)', code_line):
            m_param = re.search(r'public\s+.*\(\s*String\s+([a-zA-Z0-9_]+)', code_line)
            if m_param:
                param_name = m_param.group(1)
                if any(f"{param_name}." in l and f"{param_name} == null" not in code for l in lines[i:]):
                    findings.append(normalize_finding(
                        tool="checkstyle (builtin analyzer)",
                        rule_id="checkstyle:NullPointerRisk",
                        line=i,
                        message=f"Unchecked method invocation on parameter '{param_name}' may throw NullPointerException",
                        severity="medium",
                        category="bug",
                        cwe="CWE-476",
                        tool_available=False,
                        evidence_type="builtin_pattern_rule"
                    ))
        # 7. Division by zero risk (CWE-369)
        if re.search(r'/\s*([a-zA-Z0-9_]*(?:count|size|length|total|items))\b', code_line):
            if "?" not in code_line and "if (" not in code_line and "if(" not in code_line and "!= 0" not in code_line and "> 0" not in code_line:
                findings.append(normalize_finding(
                    tool="checkstyle (builtin analyzer)",
                    rule_id="checkstyle:DivisionByZero",
                    line=i,
                    message="Potential division by zero without guard check on denominator",
                    severity="high",
                    category="bug",
                    cwe="CWE-369",
                    tool_available=False,
                    evidence_type="builtin_pattern_rule"
                ))

    # 8. Syntax validation (unmatched braces/parentheses/brackets or unclosed comment)
    has_unmatched = (
        code.count("{") != code.count("}") or
        code.count("(") != code.count(")") or
        code.count("[") != code.count("]") or
        ("/*" in code and "*/" not in code)
    )
    if has_unmatched:
        findings.append(normalize_finding(
            tool="checkstyle (builtin analyzer)",
            rule_id="checkstyle:SyntaxError",
            line=len(lines),
            message="Syntax error: unmatched braces, brackets, parentheses, or unclosed comment in Java source code",
            severity="critical",
            category="bug",
            cwe="CWE-1078",
            tool_available=False,
            evidence_type="builtin_pattern_rule"
        ))

    return findings


