def run_python_linters(code: str, return_telemetry: bool = False) -> Any:
    """
    Runs Bandit (Security), Pylint (Quality), and safe AST check concurrently on Python source code.
    Maintains deterministic isolation, bounded concurrency, and accurate per-tool execution telemetry.
    """
    findings: List[Dict[str, Any]] = []
    tools_exec: List[Dict[str, Any]] = []

    with tempfile.NamedTemporaryFile(suffix=".py", mode="w", delete=False, encoding="utf-8") as f:
        f.write(code)
        temp_path = f.name

    try:
        bandit_exe = shutil.which("bandit")
        pylint_exe = shutil.which("pylint")

        def _run_bandit():
            if not bandit_exe:
                return [], {
                    "tool": "bandit",
                    "available": False,
                    "binary_path": None,
                    "execution_time_ms": 0.0,
                    "exit_code": None,
                    "status": "unavailable",
                    "findings_count": 0,
                    "error": "Binary 'bandit' not found in PATH. Install with: pip install bandit"
                }
            code_ret, stdout, stderr, dur_ms, err = _safe_run_subprocess(
                [bandit_exe, "-f", "json", "-q", temp_path],
                timeout=10
            )
            b_findings = []
            if stdout:
                try:
                    data = json.loads(stdout)
                    for item in data.get("results", []):
                        cwe_id = item.get("issue_cwe", {}).get("id")
                        cwe_str = f"CWE-{cwe_id}" if cwe_id else "CWE-Unknown"
                        col_no = item.get("col_offset", 1) or 1
                        b_findings.append(normalize_finding(
                            tool="bandit",
                            rule_id=f"Bandit:{item.get('test_id', 'B000')}",
                            line=item.get("line_number", 1),
                            column=col_no,
                            message=item.get("issue_text", "Security issue detected"),
                            severity=item.get("issue_severity", "medium").lower(),
                            category="security",
                            cwe=cwe_str,
                            tool_available=True,
                            evidence_type="native_tool_output"
                        ))
                except Exception:
                    pass
            status_str = "findings_detected" if b_findings else "clean"
            if err:
                status_str = "error"
            return b_findings, {
                "tool": "bandit",
                "available": True,
                "binary_path": bandit_exe,
                "execution_time_ms": dur_ms,
                "exit_code": code_ret,
                "status": status_str,
                "findings_count": len(b_findings),
                "error": err
            }

        def _run_pylint():
            if not pylint_exe:
                return [], {
                    "tool": "pylint",
                    "available": False,
                    "binary_path": None,
                    "execution_time_ms": 0.0,
                    "exit_code": None,
                    "status": "unavailable",
                    "findings_count": 0,
                    "error": "Binary 'pylint' not found in PATH. Install with: pip install pylint"
                }
            code_ret, stdout, stderr, dur_ms, err = _safe_run_subprocess(
                [pylint_exe, "--output-format=json", "--disable=all", "--enable=E,W,C0301,R0903", "--persistent=n", "--score=n", temp_path],
                timeout=12
            )
            p_findings = []
            if stdout:
                try:
                    data = json.loads(stdout)
                    for item in data:
                        sev = "low"
                        if item.get("type") in ["error", "fatal"]:
                            sev = "high"
                        elif item.get("type") == "warning":
                            sev = "medium"

                        col_no = item.get("column", 1) or 1
                        p_findings.append(normalize_finding(
                            tool="pylint",
                            rule_id=f"Pylint:{item.get('symbol', 'C0001')}",
                            line=item.get("line", 1),
                            column=col_no,
                            message=item.get("message", "Lint finding"),
                            severity=sev,
                            category="bug" if sev in ["high", "medium"] else "style",
                            cwe="CWE-1078",
                            tool_available=True,
                            evidence_type="native_tool_output"
                        ))
                except Exception:
                    pass
            status_str = "findings_detected" if p_findings else "clean"
            if err:
                status_str = "error"
            return p_findings, {
                "tool": "pylint",
                "available": True,
                "binary_path": pylint_exe,
                "execution_time_ms": dur_ms,
                "exit_code": code_ret,
                "status": status_str,
                "findings_count": len(p_findings),
                "error": err
            }

        def _run_ast():
            ast_start = time.perf_counter()
            ast_findings = []
            try:
                compile(code, "<string>", "exec")
            except (SyntaxError, IndentationError, ValueError) as e:
                ast_findings.append(normalize_finding(
                    tool="python-ast",
                    rule_id="Python:SyntaxError",
                    line=getattr(e, "lineno", 1) or 1,
                    column=getattr(e, "offset", 1) or 1,
                    message=f"SyntaxError: {str(e)}",
                    severity="critical",
                    category="bug",
                    cwe="CWE-1078",
                    tool_available=True,
                    evidence_type="compiler_syntax_check"
                ))
            ast_dur = round((time.perf_counter() - ast_start) * 1000, 2)
            return ast_findings, {
                "tool": "python-ast",
                "available": True,
                "binary_path": "in-memory://compile",
                "execution_time_ms": ast_dur,
                "exit_code": 1 if ast_findings else 0,
                "status": "findings_detected" if ast_findings else "clean",
                "findings_count": len(ast_findings),
                "error": None
            }

        # Concurrently execute Bandit, Pylint, and AST checks
        with ThreadPoolExecutor(max_workers=3) as executor:
            fut_bandit = executor.submit(_run_bandit)
            fut_pylint = executor.submit(_run_pylint)
            fut_ast = executor.submit(_run_ast)

            b_findings, b_exec = fut_bandit.result()
            p_findings, p_exec = fut_pylint.result()
            a_findings, a_exec = fut_ast.result()

        findings.extend(b_findings)
        tools_exec.append(b_exec)

        findings.extend(p_findings)
        tools_exec.append(p_exec)

        findings.extend(a_findings)
        tools_exec.append(a_exec)

        # 4. Built-in deterministic pattern analysis (baseline coverage)
        det_start = time.perf_counter()
        existing_keys = {(f.get("line"), f.get("cwe")) for f in findings}
        builtin_added = 0
        for df in _deterministic_python_scan(code):
            if (df.get("line"), df.get("cwe")) not in existing_keys:
                findings.append(df)
                builtin_added += 1
        det_dur = round((time.perf_counter() - det_start) * 1000, 2)
        tools_exec.append({
            "tool": "builtin-python-analyzer",
            "available": True,
            "binary_path": "builtin://deterministic-rules",
            "execution_time_ms": det_dur,
            "exit_code": 0,
            "status": "findings_detected" if builtin_added > 0 else "clean",
            "findings_count": builtin_added,
            "error": None
        })

    finally:
        try:
            os.remove(temp_path)
        except OSError:
            pass

    if return_telemetry:
        return findings, tools_exec
    return findings


def _deterministic_python_scan(code: str) -> List[Dict[str, Any]]:
    """Deterministic static analysis rules for Python matching Bandit & Pylint rule IDs."""
    findings = []
    lines = code.split("\n")

    for i, line in enumerate(lines, 1):
        code_line = line.split("#")[0].strip()
        if not code_line:
            continue

        # 1. SQL Injection detection (Bandit B608, CWE-89)
        if re.search(r'(SELECT|UPDATE|INSERT|DELETE).*(\+|%|\.format|f[\'"]).*WHERE', code_line, re.IGNORECASE):
            findings.append(normalize_finding(
                tool="bandit (builtin analyzer)",
                rule_id="Bandit:B608",
                line=i,
                message="Possible SQL injection vector through string-based query construction; use parameterized queries",
                severity="critical",
                category="security",
                cwe="CWE-89",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        # 2. Command Injection (Bandit B605, CWE-78)
        if re.search(r'os\.system\(|subprocess\.Popen\(.*shell\s*=\s*True', code_line):
            findings.append(normalize_finding(
                tool="bandit (builtin analyzer)",
                rule_id="Bandit:B605",
                line=i,
                message="Starting a process with a partial executable path or shell=True allows command injection",
                severity="critical",
                category="security",
                cwe="CWE-78",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        # 3. Hardcoded Secrets (Bandit B105, CWE-798)
        if re.search(r'(SECRET|TOKEN|API_KEY|PASSWORD)\s*=\s*["\'][A-Za-z0-9_\-]{16,}["\']', code_line, re.IGNORECASE):
            findings.append(normalize_finding(
                tool="bandit (builtin analyzer)",
                rule_id="Bandit:B105",
                line=i,
                message="Possible hardcoded password or authentication token in source code",
                severity="high",
                category="security",
                cwe="CWE-798",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        # 4. Path Traversal (Bandit B108, CWE-22)
        if re.search(r'os\.path\.join\([^,]+,\s*[a-zA-Z0-9_]+\)', code_line) and "basename" not in code_line and "open(" in code:
            findings.append(normalize_finding(
                tool="bandit (builtin analyzer)",
                rule_id="Bandit:B108",
                line=i,
                message="File access path joined without path traversal sanitization (os.path.basename / resolve)",
                severity="high",
                category="security",
                cwe="CWE-22",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        # 5. Insecure Deserialization / Pickle (Bandit B301, CWE-502)
        if "pickle.loads(" in code_line or "_pickle.loads(" in code_line:
            findings.append(normalize_finding(
                tool="bandit (builtin analyzer)",
                rule_id="Bandit:B301",
                line=i,
                message="Pickle deserialization of untrusted data leads to arbitrary code execution",
                severity="critical",
                category="security",
                cwe="CWE-502",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        # 6. Weak cryptographic hash (Bandit B324, CWE-327)
        if re.search(r'hashlib\.(md5|sha1)\(', code_line):
            findings.append(normalize_finding(
                tool="bandit (builtin analyzer)",
                rule_id="Bandit:B324",
                line=i,
                message="Use of weak cryptographic hash (MD5/SHA1); use SHA-256 or stronger",
                severity="medium",
                category="security",
                cwe="CWE-327",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        # 7. Division by zero risk (Pylint division-by-zero, CWE-369)
        if re.search(r'/\s*([a-zA-Z0-9_]*(?:count|size|length|total|denom|divisor|n|m|len|num|items)\b|0)', code_line):
            if "if " not in code_line and "!= 0" not in code_line and "> 0" not in code_line and "len(" not in code_line and "?" not in code_line:
                findings.append(normalize_finding(
                    tool="pylint (builtin analyzer)",
                    rule_id="Pylint:division-by-zero",
                    line=i,
                    message="Potential division by zero without guard check on denominator",
                    severity="high",
                    category="bug",
                    cwe="CWE-369",
                    tool_available=False,
                    evidence_type="builtin_pattern_rule"
                ))
        # 8. Broad / swallowed exception (Pylint bare-except, CWE-390)
        if re.search(r'except(\s+Exception)?\s*:\s*pass', code_line) or (re.search(r'except(\s+Exception)?\s*:\s*$', code_line) and i < len(lines) and lines[i].strip() == "pass"):
            findings.append(normalize_finding(
                tool="pylint (builtin analyzer)",
                rule_id="Pylint:bare-except",
                line=i,
                message="Silent exception swallowing hides runtime crashes and security failures",
                severity="medium",
                category="bug",
                cwe="CWE-390",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        # 9. Inefficient string concatenation in loop (Pylint consider-using-join, Performance)
        if re.search(r'\b[a-zA-Z0-9_]+\s*\+=\s*[a-zA-Z0-9_]+', code_line) and "for " in code and ("data" in code or "items" in code or "chunk" in code_line):
            findings.append(normalize_finding(
                tool="pylint (builtin analyzer)",
                rule_id="Pylint:consider-using-join",
                line=i,
                message="Repeated string concatenation (+=) in loop creates quadratic heap copies; use ''.join()",
                severity="low",
                category="performance",
                cwe="CWE-1078",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        # 10. Potential unvalidated dictionary key access (Pylint unsubscriptable-object, CWE-754)
        if re.search(r'return\s+.*\[["\'][a-zA-Z0-9_]+["\']\]', code_line) and ".get(" not in code_line:
            findings.append(normalize_finding(
                tool="pylint (builtin analyzer)",
                rule_id="Pylint:unsubscriptable-object",
                line=i,
                message="Direct dictionary key access without membership validation may raise KeyError",
                severity="low",
                category="bug",
                cwe="CWE-754",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
    return findings


