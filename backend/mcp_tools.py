def _deterministic_ruby_scan(code: str) -> List[Dict[str, Any]]:
    """Deterministic Ruby static analysis engine matching RuboCop rule IDs."""
    findings = []
    lines = code.split("\n")
    for i, line in enumerate(lines, 1):
        code_line = line.split("#")[0].strip()
        if not code_line:
            continue

        if re.search(r'(SELECT|UPDATE|INSERT|DELETE).*#\{', code_line, re.IGNORECASE):
            findings.append(normalize_finding(
                tool="rubocop (builtin analyzer)",
                rule_id="rubocop:Security/SqlInjection",
                line=i,
                message="SQL query built via string interpolation; use query parameters",
                severity="critical",
                category="security",
                cwe="CWE-89",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        if re.search(r'`wkhtmltopdf.*#\{', code_line) or re.search(r'system\(.*#\{', code_line):
            findings.append(normalize_finding(
                tool="rubocop (builtin analyzer)",
                rule_id="rubocop:Security/CommandInjection",
                line=i,
                message="Command injection vulnerability detected in backticks shell execution",
                severity="critical",
                category="security",
                cwe="CWE-78",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        if "Marshal.load(" in code_line:
            findings.append(normalize_finding(
                tool="rubocop (builtin analyzer)",
                rule_id="rubocop:Security/MarshalLoad",
                line=i,
                message="Avoid using Marshal.load with untrusted data due to object injection",
                severity="critical",
                category="security",
                cwe="CWE-502",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        if re.search(r'API_KEY\s*=\s*["\'][A-Za-z0-9_\-]{16,}["\']', code_line):
            findings.append(normalize_finding(
                tool="rubocop (builtin analyzer)",
                rule_id="rubocop:Security/HardcodedSecret",
                line=i,
                message="Hardcoded production API key in constant declaration",
                severity="high",
                category="security",
                cwe="CWE-798",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))

    # Syntax validation (unmatched block keywords or braces)
    code_no_comments = re.sub(r'#.*$', '', code, flags=re.MULTILINE)
    code_no_strings = re.sub(r'("[^"\\]*(?:\\.[^"\\]*)*"|\'[^\'\\]*(?:\\.[^\'\\]*)*\')', '', code_no_comments)
    def_count = len(re.findall(r'\b(def|class|module|do)\b', code_no_strings))
    end_count = len(re.findall(r'\bend\b', code_no_strings))
    has_unmatched = (
        def_count != end_count or
        code.count("{") != code.count("}") or
        code.count("(") != code.count(")") or
        code.count("[") != code.count("]")
    )
    if has_unmatched:
        findings.append(normalize_finding(
            tool="rubocop (builtin analyzer)",
            rule_id="rubocop:Lint/Syntax",
            line=len(lines),
            message=f"Syntax error: unmatched block keywords or delimiters ({def_count} def/class/do vs {end_count} end)",
            severity="critical",
            category="bug",
            cwe="CWE-1078",
            tool_available=False,
            evidence_type="builtin_pattern_rule"
        ))

    return findings


