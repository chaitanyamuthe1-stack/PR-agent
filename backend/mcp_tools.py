def run_javascript_linters(code: str, return_telemetry: bool = False) -> Any:
    """
    Runs ESLint on JavaScript source code.
    Runs safe syntax verification via node --check (zero execution, V8 parse only).
    Never claims a missing tool ran.
    """
    findings: List[Dict[str, Any]] = []
    tools_exec: List[Dict[str, Any]] = []

    with tempfile.NamedTemporaryFile(suffix=".js", mode="w", delete=False, encoding="utf-8") as f:
        f.write(code)
        temp_path = f.name

    try:
        # 1. Run ESLint (if installed)
        eslint_exe = shutil.which("eslint")
        if eslint_exe:
            code_ret, stdout, stderr, dur_ms, err = _safe_run_subprocess(
                [eslint_exe, "-f", "json", temp_path],
                timeout=10
            )
            es_findings = []
            if stdout:
                try:
                    data = json.loads(stdout)
                    for file_res in data:
                        for msg in file_res.get("messages", []):
                            sev = "high" if msg.get("severity") == 2 else "medium"
                            es_findings.append(normalize_finding(
                                tool="eslint",
                                rule_id=f"eslint:{msg.get('ruleId', 'lint')}",
                                line=msg.get("line", 1),
                                column=msg.get("column", 1),
                                message=msg.get("message", "Lint finding"),
                                severity=sev,
                                category="security" if "security" in str(msg.get("ruleId")) else "bug",
                                cwe="CWE-1078",
                                tool_available=True,
                                evidence_type="native_tool_output"
                            ))
                except Exception:
                    pass

            findings.extend(es_findings)
            tools_exec.append({
                "tool": "eslint",
                "available": True,
                "binary_path": eslint_exe,
                "execution_time_ms": dur_ms,
                "exit_code": code_ret,
                "status": "findings_detected" if es_findings else "clean",
                "findings_count": len(es_findings),
                "error": err
            })
        else:
            tools_exec.append({
                "tool": "eslint",
                "available": False,
                "binary_path": None,
                "execution_time_ms": 0.0,
                "exit_code": None,
                "status": "unavailable",
                "findings_count": 0,
                "error": "Binary 'eslint' not found in PATH. Install with: npm install -g eslint"
            })

        # 2. Safe syntax check via Node.js runtime (node --check: zero execution, V8 parse only)
        node_exe = shutil.which("node")
        if node_exe:
            code_ret, stdout, stderr, dur_ms, err = _safe_run_subprocess(
                [node_exe, "--check", temp_path],
                timeout=5
            )
            node_findings = []
            if code_ret != 0 and stderr:
                m_err = re.search(r':(\d+)\r?\n', stderr)
                line_no = int(m_err.group(1)) if m_err else 1
                m_msg = re.search(r'(SyntaxError:[^\n\r]+)', stderr)
                err_msg = m_msg.group(1) if m_msg else "JavaScript syntax error detected by Node.js"
                node_findings.append(normalize_finding(
                    tool="node",
                    rule_id="Node:SyntaxError",
                    line=line_no,
                    message=err_msg,
                    severity="critical",
                    category="bug",
                    cwe="CWE-1078",
                    tool_available=True,
                    evidence_type="compiler_syntax_check"
                ))

            findings.extend(node_findings)
            tools_exec.append({
                "tool": "node",
                "available": True,
                "binary_path": node_exe,
                "execution_time_ms": dur_ms,
                "exit_code": code_ret,
                "status": "findings_detected" if node_findings else "clean",
                "findings_count": len(node_findings),
                "error": err
            })
        else:
            tools_exec.append({
                "tool": "node",
                "available": False,
                "binary_path": None,
                "execution_time_ms": 0.0,
                "exit_code": None,
                "status": "unavailable",
                "findings_count": 0,
                "error": "Runtime 'node' not found in PATH for safe syntax validation."
            })

        # 3. Built-in deterministic pattern analysis (zero-dependency baseline)
        det_start = time.perf_counter()
        existing_keys = {(f.get("line"), f.get("cwe")) for f in findings}
        builtin_added = 0
        for df in _deterministic_javascript_scan(code):
            if (df.get("line"), df.get("cwe")) not in existing_keys:
                findings.append(df)
                builtin_added += 1
        det_dur = round((time.perf_counter() - det_start) * 1000, 2)
        tools_exec.append({
            "tool": "builtin-javascript-analyzer",
            "available": True,
            "binary_path": "builtin://deterministic-rules",
            "execution_time_ms": det_dur,
            "exit_code": 0,
            "status": "findings_detected" if builtin_added > 0 else "clean",
            "findings_count": builtin_added,
            "error": None
        })

    finally:
        try:
            os.remove(temp_path)
        except OSError:
            pass

    if return_telemetry:
        return findings, tools_exec
    return findings


def _deterministic_javascript_scan(code: str) -> List[Dict[str, Any]]:
    """Deterministic JavaScript static analysis engine matching ESLint rule IDs."""
    findings = []
    lines = code.split("\n")
    for i, line in enumerate(lines, 1):
        code_line = line.split("//")[0].strip()
        if not code_line:
            continue

        if re.search(r'\beval\(', code_line):
            findings.append(normalize_finding(
                tool="eslint (builtin analyzer)",
                rule_id="eslint:no-eval",
                line=i,
                message="eval can be harmful; dynamically evaluated user code leads to remote code execution",
                severity="critical",
                category="security",
                cwe="CWE-95",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        if re.search(r'res\.send\(.*req\.query', code_line):
            findings.append(normalize_finding(
                tool="eslint (builtin analyzer)",
                rule_id="eslint:security/detect-xss",
                line=i,
                message="Reflected Cross-Site Scripting (XSS) via unescaped req.query parameter",
                severity="critical",
                category="security",
                cwe="CWE-79",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        if re.search(r'target\[key\]\s*=\s*payload\[key\]', code_line):
            findings.append(normalize_finding(
                tool="eslint (builtin analyzer)",
                rule_id="eslint:prototype-pollution",
                line=i,
                message="Object assignment without checking __proto__ or constructor can pollute prototype",
                severity="high",
                category="security",
                cwe="CWE-1321",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        if re.search(r'(?<![=!])==(?!=)\s*["\']', code_line) or re.search(r'["\']\s*(?<![=!])==(?!=)', code_line):
            findings.append(normalize_finding(
                tool="eslint (builtin analyzer)",
                rule_id="eslint:eqeqeq",
                line=i,
                message="Expected '===' and instead saw '==' (loose equality type coercion)",
                severity="low",
                category="style",
                cwe="CWE-480",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))
        if re.search(r'(JWT_SECRET|API_KEY)\s*=\s*["\'][A-Za-z0-9_\-]{16,}["\']', code_line):
            findings.append(normalize_finding(
                tool="eslint (builtin analyzer)",
                rule_id="eslint:no-secrets",
                line=i,
                message="Hardcoded secret token found in server-side script",
                severity="high",
                category="security",
                cwe="CWE-798",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))

    # Syntax validation (unmatched braces/parentheses/brackets or unclosed comment)
    has_unmatched = (
        code.count("{") != code.count("}") or
        code.count("(") != code.count(")") or
        code.count("[") != code.count("]") or
        ("/*" in code and "*/" not in code)
    )
    if has_unmatched:
        findings.append(normalize_finding(
            tool="eslint (builtin analyzer)",
            rule_id="eslint:syntax-error",
            line=len(lines),
            message="Parsing error: unmatched braces, brackets, parentheses, or unclosed syntax in JavaScript source code",
            severity="critical",
            category="bug",
            cwe="CWE-1078",
            tool_available=False,
            evidence_type="builtin_pattern_rule"
        ))

    return findings


