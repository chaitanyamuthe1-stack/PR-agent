def run_static_analysis(code: str, language: str, config_hash: Optional[str] = None) -> Dict[str, Any]:
    """
    Main MCP dispatching entry point.
    Routes language to appropriate tools and safe syntax checks.
    Captures tool exit codes, findings, execution time, and tool availability.
    Normalizes output into common finding schema.
    Distinguishes clean analysis from unavailable analysis and partial coverage.
    Thread-safe LRU caching prevents duplicate analysis passes.
    """
    lang = language.lower().strip()
    tools_invoked = get_mcp_tools_for_language(lang, truthful=True)
    findings: List[Dict[str, Any]] = []
    tools_execution: List[Dict[str, Any]] = []

    # 1. Evaluate simulation flags first
    if os.getenv("PR_AGENT_SIMULATE_MCP_FAIL") == "1":
        return {
            "language": lang,
            "coverage": "unavailable",
            "coverage_explanation": "Model Context Protocol dispatch layer offline / communication failure",
            "tools_invoked": tools_invoked,
            "tools_execution": [],
            "total_findings": 1,
            "findings": [normalize_finding(
                tool="mcp",
                rule_id="MCP:TOOL_UNAVAILABLE",
                line=1,
                message="MCP UNAVAILABLE: Model Context Protocol dispatch layer offline / communication failure",
                severity="high",
                category="bug",
                cwe="CWE-1078",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            )],
            "status": "MCP UNAVAILABLE"
        }

    if os.getenv("PR_AGENT_SIMULATE_ANALYZER_FAIL") == "1":
        return {
            "language": lang,
            "coverage": "unavailable",
            "coverage_explanation": "Static analyzer binary execution failed or linter crashed",
            "tools_invoked": tools_invoked,
            "tools_execution": [],
            "total_findings": 1,
            "findings": [normalize_finding(
                tool="mcp",
                rule_id="MCP:ANALYZER_UNAVAILABLE",
                line=1,
                message="ANALYZER UNAVAILABLE: Static analyzer binary execution failed or linter crashed",
                severity="high",
                category="bug",
                cwe="CWE-1078",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            )],
            "status": "ANALYZER UNAVAILABLE"
        }

    # 2. Thread-safe composite LRU cache check for identical code analysis
    # Uses file/code hash, tool versions hash, and configuration hash
    code_hash = hashlib.sha256(code.encode("utf-8")).hexdigest()
    tool_ver_hash = _get_tool_versions_hash_for_lang(lang)
    cfg_hash = config_hash or _get_tool_config_hash_for_lang(lang)
    composite_cache_key = f"{lang}:{code_hash}:{tool_ver_hash}:{cfg_hash}"
    legacy_cache_key = hashlib.sha256(f"{lang}:{code}".encode("utf-8")).hexdigest()

    with _STATIC_CACHE_LOCK:
        _CACHE_STATS["total_queries"] += 1
        cached_result = None
        if composite_cache_key in _STATIC_CACHE:
            cached_result = dict(_STATIC_CACHE[composite_cache_key])
        elif config_hash is None and legacy_cache_key in _STATIC_CACHE:
            cached_result = dict(_STATIC_CACHE[legacy_cache_key])

        if cached_result is not None:
            _CACHE_STATS["hits"] += 1
            cached_result["cached"] = True
            cached_result["cache_key"] = composite_cache_key
            return cached_result
        _CACHE_STATS["misses"] += 1

    # 3. Route to language-specific runners
    try:
        if lang == "python":
            findings, tools_execution = run_python_linters(code, return_telemetry=True)
        elif lang in ["cpp", "c++"]:
            findings, tools_execution = run_cpp_linters(code, is_c=False, return_telemetry=True)
        elif lang == "c":
            findings, tools_execution = run_cpp_linters(code, is_c=True, return_telemetry=True)
        elif lang == "java":
            findings, tools_execution = run_java_linters(code, return_telemetry=True)
        elif lang in ["javascript", "js", "typescript", "ts"]:
            findings, tools_execution = run_javascript_linters(code, return_telemetry=True)
        elif lang == "ruby":
            findings, tools_execution = run_ruby_linters(code, return_telemetry=True)
        else:
            findings, tools_execution = run_python_linters(code, return_telemetry=True)
    except Exception as e:
        status_msg = f"ANALYZER UNAVAILABLE: {str(e)}"
        return {
            "language": lang,
            "coverage": "unavailable",
            "coverage_explanation": status_msg,
            "tools_invoked": tools_invoked,
            "tools_execution": [],
            "total_findings": 1,
            "findings": [normalize_finding(
                tool="mcp",
                rule_id="MCP:ANALYZER_UNAVAILABLE",
                line=1,
                message=status_msg,
                severity="high",
                category="bug",
                cwe="CWE-1078",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            )],
            "status": "ANALYZER UNAVAILABLE"
        }

    # 4. Assess truthful coverage and clean status
    target_tools = LANGUAGE_TOOL_MAPPING.get(lang if lang in LANGUAGE_TOOL_MAPPING else "python", ["pylint"])
    missing_target_tools = []
    active_target_tools = []
    for t in target_tools:
        if shutil.which(t):
            active_target_tools.append(t)
        else:
            missing_target_tools.append(t)

    is_full_coverage = (len(missing_target_tools) == 0)
    coverage = "full" if is_full_coverage else "partial"

    if is_full_coverage:
        coverage_explanation = f"All intended language-specific tools ({', '.join(active_target_tools)}) ran natively on the host system."
    else:
        missing_str = ", ".join(missing_target_tools)
        active_str = ", ".join(active_target_tools) or "none"
        hints = [TOOL_CATALOG[m]["install_cmd"] for m in missing_target_tools if m in TOOL_CATALOG]
        hint_str = " | ".join(hints) if hints else "See documentation"
        coverage_explanation = (
            f"Native tool(s) [{missing_str}] are not installed in PATH. "
            f"Analysis executed with active tools [{active_str}] and built-in deterministic rule engine. "
            f"To achieve 100% native coverage, install missing tools: {hint_str}"
        )

    if len(findings) == 0:
        status = "clean" if is_full_coverage else "clean (partial coverage)"
    else:
        status = "findings_detected"

    result = {
        "language": lang,
        "coverage": coverage,
        "coverage_explanation": coverage_explanation,
        "tools_invoked": tools_invoked,
        "tools_execution": tools_execution,
        "total_findings": len(findings),
        "findings": findings,
        "status": status,
        "cache_key": composite_cache_key,
        "cached": False
    }

    with _STATIC_CACHE_LOCK:
        _STATIC_CACHE[composite_cache_key] = result
        if config_hash is None:
            _STATIC_CACHE[legacy_cache_key] = result
        while len(_STATIC_CACHE) > MAX_STATIC_CACHE:
            oldest = next(iter(_STATIC_CACHE))
            del _STATIC_CACHE[oldest]

    return result
