def run_cpp_linters(code: str, is_c: bool = False, return_telemetry: bool = False) -> Any:
    """
    Runs Cppcheck on C/C++ source code.
    Runs optional compiler-based syntax checks (-fsyntax-only) when gcc/g++ is available.
    Never claims a missing tool ran.
    """
    findings: List[Dict[str, Any]] = []
    tools_exec: List[Dict[str, Any]] = []
    suffix = ".c" if is_c else ".cpp"

    with tempfile.NamedTemporaryFile(suffix=suffix, mode="w", delete=False, encoding="utf-8") as f:
        f.write(code)
        temp_path = f.name

    try:
        # 1. Run Cppcheck (Static Analyzer)
        cppcheck_exe = shutil.which("cppcheck")
        if cppcheck_exe:
            code_ret, stdout, stderr, dur_ms, err = _safe_run_subprocess(
                [cppcheck_exe, "--enable=all", "--inconclusive", "--template={file}:{line}:{column}: ({severity}) {id}: {message}", temp_path],
                timeout=12
            )
            cppcheck_findings = []
            combined_output = (stdout + "\n" + stderr).splitlines()
            for line in combined_output:
                m = re.search(r':(\d+):(?:(\d+):)?\s*\(([a-z]+)\)\s*([a-zA-Z0-9_]+)?:\s*(.*)', line)
                if m:
                    lineno = int(m.group(1))
                    colno = int(m.group(2)) if m.group(2) else 1
                    sev_str = m.group(3).lower()
                    rule_str = m.group(4) or "warning"
                    msg = m.group(5)

                    sev = "high" if "error" in sev_str else ("medium" if "warning" in sev_str else "low")
                    cat = "security" if any(w in msg.lower() for w in ["overflow", "bounds", "leak", "free"]) else "bug"
                    cwe_str = "CWE-120" if "overflow" in msg.lower() or "bounds" in msg.lower() else ("CWE-401" if "leak" in msg.lower() else "CWE-1078")

                    cppcheck_findings.append(normalize_finding(
                        tool="cppcheck",
                        rule_id=f"cppcheck:{rule_str}",
                        line=lineno,
                        column=colno,
                        message=msg,
                        severity=sev,
                        category=cat,
                        cwe=cwe_str,
                        tool_available=True,
                        evidence_type="native_tool_output"
                    ))

            findings.extend(cppcheck_findings)
            status_str = "findings_detected" if cppcheck_findings else "clean"
            if err:
                status_str = "error"
            tools_exec.append({
                "tool": "cppcheck",
                "available": True,
                "binary_path": cppcheck_exe,
                "execution_time_ms": dur_ms,
                "exit_code": code_ret,
                "status": status_str,
                "findings_count": len(cppcheck_findings),
                "error": err
            })
        else:
            tools_exec.append({
                "tool": "cppcheck",
                "available": False,
                "binary_path": None,
                "execution_time_ms": 0.0,
                "exit_code": None,
                "status": "unavailable",
                "findings_count": 0,
                "error": "Binary 'cppcheck' not found in PATH. Install with: choco install cppcheck (Windows) or apt install cppcheck (Linux)"
            })

        # 2. Optional compiler-based syntax checks (g++ / gcc -fsyntax-only: safe, zero execution)
        compiler_name = "gcc" if is_c else "g++"
        compiler_exe = shutil.which(compiler_name) or shutil.which("clang" if is_c else "clang++")
        if compiler_exe:
            code_ret, stdout, stderr, dur_ms, err = _safe_run_subprocess(
                [compiler_exe, "-fsyntax-only", "-Wall", "-Wextra", temp_path],
                timeout=8
            )
            comp_findings = []
            if code_ret != 0 and stderr:
                for sline in stderr.splitlines():
                    m_comp = re.search(r':(\d+):(\d+):\s*(error|warning):\s*(.*)', sline)
                    if m_comp:
                        cline, ccol, ckind, cmsg = int(m_comp.group(1)), int(m_comp.group(2)), m_comp.group(3), m_comp.group(4)
                        comp_findings.append(normalize_finding(
                            tool=compiler_name,
                            rule_id=f"{compiler_name}:{ckind}",
                            line=cline,
                            column=ccol,
                            message=cmsg,
                            severity="critical" if ckind == "error" else "medium",
                            category="bug",
                            cwe="CWE-1078",
                            tool_available=True,
                            evidence_type="compiler_syntax_check"
                        ))

            findings.extend(comp_findings)
            tools_exec.append({
                "tool": compiler_name,
                "available": True,
                "binary_path": compiler_exe,
                "execution_time_ms": dur_ms,
                "exit_code": code_ret,
                "status": "findings_detected" if comp_findings else "clean",
                "findings_count": len(comp_findings),
                "error": err
            })
        else:
            tools_exec.append({
                "tool": compiler_name,
                "available": False,
                "binary_path": None,
                "execution_time_ms": 0.0,
                "exit_code": None,
                "status": "unavailable",
                "findings_count": 0,
                "error": f"Compiler '{compiler_name}' not found in PATH for optional syntax validation."
            })

        # 3. Built-in deterministic pattern analysis (zero-dependency guarantee)
        det_start = time.perf_counter()
        existing_keys = {(f.get("line"), f.get("cwe")) for f in findings}
        builtin_added = 0
        for df in _deterministic_cpp_scan(code):
            if (df.get("line"), df.get("cwe")) not in existing_keys:
                findings.append(df)
                builtin_added += 1
        det_dur = round((time.perf_counter() - det_start) * 1000, 2)
        tools_exec.append({
            "tool": "builtin-cpp-analyzer",
            "available": True,
            "binary_path": "builtin://deterministic-rules",
            "execution_time_ms": det_dur,
            "exit_code": 0,
            "status": "findings_detected" if builtin_added > 0 else "clean",
            "findings_count": builtin_added,
            "error": None
        })

    finally:
        try:
            os.remove(temp_path)
        except OSError:
            pass

    if return_telemetry:
        return findings, tools_exec
    return findings


def _deterministic_cpp_scan(code: str) -> List[Dict[str, Any]]:
    """Deterministic C/C++ static analysis engine detecting runtime, memory, and bounds flaws."""
    findings = []
    lines = code.split("\n")

    for i, line in enumerate(lines, 1):
        code_line = line.split("//")[0].strip()
        if not code_line:
            continue

        # 1. Division by zero risk (CWE-369)
        # Avoid matching lines guarded by ternary (total > 0 ?), if checks, or comments
        if re.search(r'/\s*(?:[a-zA-Z0-9_]+(?:\.|->))?([a-zA-Z0-9_]*(?:count|size|length|total|denom|divisor|n|m|len|num|items|elements)(?:\(\))?|0)\b', code_line):
            if "?" not in code_line and "if (" not in code_line and "if(" not in code_line and "!= 0" not in code_line and "> 0" not in code_line and "len(" not in code_line:
                findings.append(normalize_finding(
                    tool="cppcheck (builtin analyzer)",
                    rule_id="cppcheck:zerodiv",
                    line=i,
                    message="Potential division by zero without guard check on denominator",
                    severity="high",
                    category="bug",
                    cwe="CWE-369",
                    tool_available=False,
                    evidence_type="builtin_pattern_rule"
                ))

        # 2. Assignment inside conditional expression (CWE-481)
        if re.search(r'\bif\s*\(\s*[a-zA-Z0-9_]+\s*=\s*[^=][^;)]*\)', code_line):
            findings.append(normalize_finding(
                tool="cppcheck (builtin analyzer)",
                rule_id="cppcheck:assignmentInCondition",
                line=i,
                message="Assignment operator '=' used inside conditional expression instead of comparison '=='",
                severity="high",
                category="bug",
                cwe="CWE-481",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))

        # 3. Dangling pointer / reference to local stack variable (CWE-562)
        if re.search(r'return\s+&[a-zA-Z0-9_]+\s*;', code_line):
            findings.append(normalize_finding(
                tool="cppcheck (builtin analyzer)",
                rule_id="cppcheck:danglingStackReference",
                line=i,
                message="Function returns address of a local stack variable, resulting in a dangling pointer",
                severity="critical",
                category="bug",
                cwe="CWE-562",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))

        # 4. Memory Leaks: new without delete (CWE-401)
        if re.search(r'\bnew\s+[a-zA-Z0-9_:]+(\[|\()', code_line) and "delete" not in code and "unique_ptr" not in code and "shared_ptr" not in code:
            findings.append(normalize_finding(
                tool="cppcheck (builtin analyzer)",
                rule_id="cppcheck:memleak",
                line=i,
                message="Memory allocated on heap with 'new' without matching 'delete' or RAII smart pointer",
                severity="high",
                category="bug",
                cwe="CWE-401",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))

        # 5. Memory Leaks: malloc without free (CWE-401)
        if "malloc(" in code_line and "free(" not in code:
            findings.append(normalize_finding(
                tool="cppcheck (builtin analyzer)",
                rule_id="cppcheck:memleak",
                line=i,
                message="Memory allocated on heap with malloc() without matching free(); potential memory leak",
                severity="high",
                category="bug",
                cwe="CWE-401",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))

        # 6. Off-by-one loop boundary condition (CWE-193)
        if re.search(r'for\s*\([^;]+;\s*[a-zA-Z0-9_]+\s*<=\s*([a-zA-Z0-9_]+(?:\.[a-zA-Z0-9_]+\(\))?|\d+)\s*;', code_line):
            findings.append(normalize_finding(
                tool="cppcheck (builtin analyzer)",
                rule_id="cppcheck:arrayIndexOutOfBounds",
                line=i,
                message="Off-by-one array/container boundary error in loop condition ('<=' instead of '<')",
                severity="medium",
                category="bug",
                cwe="CWE-193",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))

        # 7. Null Pointer Dereference (CWE-476)
        if "getenv(" in code_line and ("strlen(" in code or "token[" in code):
            findings.append(normalize_finding(
                tool="cppcheck (builtin analyzer)",
                rule_id="cppcheck:nullPointerDereference",
                line=i,
                message="Possible NULL pointer dereference on return value of getenv()",
                severity="high",
                category="bug",
                cwe="CWE-476",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))

        # 8. Uninitialized scalar or pointer variable (CWE-457)
        if re.search(r'\b(?:int|float|double|long|bool)\s+([a-zA-Z0-9_]+)\s*;', code_line):
            m_uninit = re.search(r'\b(?:int|float|double|long|bool)\s+([a-zA-Z0-9_]+)\s*;', code_line)
            if m_uninit:
                u_var = m_uninit.group(1)
                for k in range(i, min(i + 8, len(lines))):
                    if re.search(r'\b' + u_var + r'\b', lines[k]) and f"{u_var} =" not in lines[k] and f"cin >> {u_var}" not in lines[k]:
                        findings.append(normalize_finding(
                            tool="cppcheck (builtin analyzer)",
                            rule_id="cppcheck:uninitvar",
                            line=i,
                            message=f"Scalar variable '{u_var}' declared uninitialized and read before assignment",
                            severity="high",
                            category="bug",
                            cwe="CWE-457",
                            tool_available=False,
                            evidence_type="builtin_pattern_rule"
                        ))
                        break

        # 9. Buffer overflow with unsafe C string functions (CWE-120)
        if "strcpy(" in code_line or "gets(" in code_line or "strcat(" in code_line:
            findings.append(normalize_finding(
                tool="cppcheck (builtin analyzer)",
                rule_id="cppcheck:bufferAccessOutOfBounds",
                line=i,
                message="Dangerous function call (strcpy/strcat/gets); unbounded buffer copy may overflow memory",
                severity="critical",
                category="security",
                cwe="CWE-120",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))

        # 10. Hardcoded secret / credentials (CWE-798)
        if re.search(r'(API_KEY|PASSWORD|SECRET|KEY)\s*=\s*["\'][^"\']+["\']', code_line, re.IGNORECASE) or re.search(r'char\*\s+[a-zA-Z0-9_]*(?:key|secret|token)\s*=\s*["\']', code_line, re.IGNORECASE):
            findings.append(normalize_finding(
                tool="cppcheck (builtin analyzer)",
                rule_id="cppcheck:hardcodedCredentials",
                line=i,
                message="Hardcoded sensitive token or credentials detected in source",
                severity="high",
                category="security",
                cwe="CWE-798",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))

        # 11. Unclosed file handle (CWE-404)
        if re.search(r'FILE\*\s+[a-zA-Z0-9_]+\s*=\s*fopen\(', code_line) and "fclose(" not in code:
            findings.append(normalize_finding(
                tool="cppcheck (builtin analyzer)",
                rule_id="cppcheck:resourceLeak",
                line=i,
                message="File opened with fopen() but fclose() was not found; resource descriptor leak",
                severity="high",
                category="bug",
                cwe="CWE-404",
                tool_available=False,
                evidence_type="builtin_pattern_rule"
            ))

    # 12. Syntax validation (unmatched braces/parentheses/brackets or unclosed comment)
    has_unmatched = (
        code.count("{") != code.count("}") or
        code.count("(") != code.count(")") or
        code.count("[") != code.count("]") or
        ("/*" in code and "*/" not in code)
    )
    if has_unmatched:
        findings.append(normalize_finding(
            tool="cppcheck (builtin analyzer)",
            rule_id="cppcheck:syntaxError",
            line=len(lines),
            message="Syntax error: unmatched braces, brackets, parentheses, or unclosed comment in C/C++ source code",
            severity="critical",
            category="bug",
            cwe="CWE-1078",
            tool_available=False,
            evidence_type="builtin_pattern_rule"
        ))

    return findings


