def normalize_finding(
    tool: str,
    rule_id: str,
    line: int,
    message: str,
    severity: str,
    category: str,
    cwe: str,
    column: int = 1,
    tool_available: bool = True,
    evidence_type: str = "native_tool_output"
) -> Dict[str, Any]:
    """Normalizes any tool or scanner output into the common finding schema."""
    valid_severities = {"critical", "high", "medium", "low", "info"}
    valid_categories = {"security", "bug", "style", "performance", "maintainability"}

    norm_sev = str(severity).lower().strip()
    norm_sev = norm_sev if norm_sev in valid_severities else "medium"

    norm_cat = str(category).lower().strip()
    norm_cat = norm_cat if norm_cat in valid_categories else "bug"

    norm_cwe = str(cwe).strip()
    if not norm_cwe.upper().startswith("CWE-"):
        norm_cwe = f"CWE-{norm_cwe}" if norm_cwe else "CWE-1078"

    try:
        norm_line = max(1, int(line or 1))
    except (ValueError, TypeError):
        norm_line = 1

    try:
        norm_col = max(1, int(column or 1))
    except (ValueError, TypeError):
        norm_col = 1

    return {
        "tool": str(tool).strip(),
        "rule_id": str(rule_id).strip(),
        "line": norm_line,
        "column": norm_col,
        "message": str(message).strip(),
        "severity": norm_sev,
        "category": norm_cat,
        "cwe": norm_cwe,
        "tool_available": bool(tool_available),
        "evidence_type": str(evidence_type)
    }


def _safe_run_subprocess(
    cmd: List[str],
    timeout: int = 10,
    cwd: Optional[str] = None
) -> Tuple[Optional[int], str, str, float, Optional[str]]:
    """
    Safely executes an external CLI tool without executing untrusted code.
    Returns: (exit_code, stdout, stderr, execution_time_ms, error_message)
    """
    start_t = time.perf_counter()
    try:
        proc = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=timeout,
            cwd=cwd,
            shell=False
        )
        duration_ms = round((time.perf_counter() - start_t) * 1000, 2)
        return proc.returncode, proc.stdout or "", proc.stderr or "", duration_ms, None
    except subprocess.TimeoutExpired:
        duration_ms = round((time.perf_counter() - start_t) * 1000, 2)
        return None, "", "Process execution timed out", duration_ms, f"Execution timed out after {timeout}s"
    except Exception as e:
        duration_ms = round((time.perf_counter() - start_t) * 1000, 2)
        return None, "", str(e), duration_ms, str(e)


def get_all_tools_status() -> Dict[str, Any]:
    """
    Queries the host environment for all supported static analysis tools.
    Returns installation status, paths, versions, and per-language coverage levels.
    """
    tools_status = {}
    for tool_name, meta in TOOL_CATALOG.items():
        bin_path = shutil.which(meta["executable"])
        is_installed = bool(bin_path)
        version_str = None

        if is_installed and tool_name in ["bandit", "pylint", "node"]:
            try:
                flag = "-v" if tool_name == "node" else "--version"
                p = subprocess.run([bin_path, flag], capture_output=True, text=True, timeout=3)
                if p.stdout:
                    version_str = p.stdout.splitlines()[0].strip()
            except Exception:
                version_str = "Installed"

        tools_status[tool_name] = {
            "name": tool_name,
            "installed": is_installed,
            "path": bin_path,
            "version": version_str,
            "language": meta["language"],
            "type": meta["type"],
            "install_cmd": meta["install_cmd"],
            "install_docs": meta["install_docs"],
            "description": meta["description"]
        }

    lang_coverage = {}
    for lang, primary_tools in LANGUAGE_TOOL_MAPPING.items():
        native_installed = [t for t in primary_tools if tools_status.get(t, {}).get("installed")]
        missing = [t for t in primary_tools if not tools_status.get(t, {}).get("installed")]
        has_full = len(missing) == 0

        # Check auxiliary syntax checkers
        aux_tool = None
        if lang == "javascript" and tools_status.get("node", {}).get("installed"):
            aux_tool = "node (syntax validator)"
        elif lang in ["cpp", "c"] and (tools_status.get("g++", {}).get("installed") or tools_status.get("gcc", {}).get("installed")):
            aux_tool = "gcc/g++ (syntax validator)"
        elif lang == "java" and tools_status.get("javac", {}).get("installed"):
            aux_tool = "javac (compilation validator)"
        elif lang == "ruby" and tools_status.get("ruby", {}).get("installed"):
            aux_tool = "ruby (syntax validator)"

        if aux_tool:
            native_installed.append(aux_tool)

        install_hints = [tools_status[m]["install_cmd"] for m in missing if m in tools_status]

        lang_coverage[lang] = {
            "coverage": "full" if has_full else "partial",
            "native_tools": native_installed,
            "missing_tools": missing,
            "install_hint": " | ".join(install_hints) if install_hints else "All tools present",
            "builtin_fallback": True
        }

    return {
        "tools": tools_status,
        "supported_languages": lang_coverage
    }


def get_mcp_tools_for_language(language: str, truthful: bool = False) -> List[str]:
    """Returns the MCP tools assigned to the specified programming language."""
    norm = language.lower().strip()
    base_tools = LANGUAGE_TOOL_MAPPING.get(norm, ["pylint"])
    if not truthful:
        return base_tools
    reported = []
    for tool in base_tools:
        is_native = bool(shutil.which(tool))
        status = "native" if is_native else "heuristic fallback"
        reported.append(f"{tool} ({status})")
    return reported


